/**
 * Writes lib/publicImages.generated.ts: the list of image files in public/.
 *
 * `resolvePublicImage` checks against this list instead of reading the disk,
 * because on Cloudflare Workers there is no public/ folder at render time and a
 * filesystem probe finds nothing. Run automatically by build/preview/deploy.
 */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const EXT = /\.(jpe?g|png|webp)$/i;

function walk(dir, prefix = "") {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? walk(path.join(dir, entry.name), `${prefix}${entry.name}/`)
      : EXT.test(entry.name)
        ? [`${prefix}${entry.name}`]
        : [],
  );
}

const files = walk("public").sort();

writeFileSync(
  "lib/publicImages.generated.ts",
  `/* Generated by scripts/generate-public-images.mjs - do not edit by hand. */\nexport const PUBLIC_IMAGES: ReadonlySet<string> = new Set([\n${files.map((f) => `  ${JSON.stringify(f)},`).join("\n")}\n]);\n`,
);

console.log(`Listed ${files.length} images from public/`);

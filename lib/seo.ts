/*
 * Business details, matching what `ContactSection` and `Footer` show. Kept
 * here rather than imported from those components because they are client /
 * presentational modules; if the phone, email, or address changes, update
 * both places.
 */
const ORGANIZATION_ID = `${SITE_URL}/#organization`;

export function organizationJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "OnlineStore",
    "@id": ORGANIZATION_ID,
    name: SITE_NAME,
    url: SITE_URL,
    logo: `${SITE_URL}/logo.png`,
    image: DEFAULT_OG_IMAGE.url,
    description:
      "Premium dry fruits mixed with pure honey, delivered across Pakistan with Cash on Delivery.",
    email: "info@hafiznuts.com",
    telephone: `+${WHATSAPP_NUMBER}`,
    address: {
      "@type": "PostalAddress",
      streetAddress: "Muslim Bazar",
      addressLocality: "Rahim Yar Khan",
      addressRegion: "Punjab",
      addressCountry: "PK",
    },
    areaServed: { "@type": "Country", name: "Pakistan" },
    contactPoint: {
      "@type": "ContactPoint",
      contactType: "customer service",
      telephone: `+${WHATSAPP_NUMBER}`,
      email: "info@hafiznuts.com",
      areaServed: "PK",
      availableLanguage: ["en", "ur"],
    },
    sameAs: [
      "https://www.facebook.com/people/Hafiz-Nuts/61595136471681/",
      "https://www.instagram.com/hafiznuts/",
    ],
  };
}

export function websiteJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": `${SITE_URL}/#website`,
    name: SITE_NAME,
    url: SITE_URL,
    inLanguage: "en-PK",
    publisher: { "@id": ORGANIZATION_ID },
  };
}

/**
 * Product + breadcrumb graph for a pack-size page.
 *
 * Deliberately no `aggregateRating` or `review`: the homepage testimonials are
 * not collected reviews, and marking them up would be self-serving review
 * markup, which Google ignores at best and penalises at worst.
 */
export function productJsonLd(product: Product, imagePath: string) {
  const url = `${SITE_URL}/products/${product.slug}`;
  const name = `Premium Honey & Nut Mix (${product.size})`;

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Product",
        "@id": `${url}#product`,
        name,
        description: product.description,
        image: [`${SITE_URL}${imagePath}`],
        sku: product.id,
        weight: product.size,
        category: "Dry Fruits & Nuts",
        brand: { "@type": "Brand", name: SITE_NAME },
        offers: {
          "@type": "Offer",
          url,
          price: product.pricePkr,
          priceCurrency: "PKR",
          availability: product.inStock
            ? "https://schema.org/InStock"
            : "https://schema.org/OutOfStock",
          itemCondition: "https://schema.org/NewCondition",
          seller: { "@id": ORGANIZATION_ID },
          areaServed: "PK",
          acceptedPaymentMethod: "Cash on Delivery",
          description: `${formatPkr(product.pricePkr)} for the ${product.size} pack`,
        },
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "Home", item: SITE_URL },
          { "@type": "ListItem", position: 2, name, item: url },
        ],
      },
    ],
  };
}

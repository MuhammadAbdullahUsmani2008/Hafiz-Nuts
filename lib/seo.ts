import type { Metadata } from "next";

import { formatPkr, SITE_URL, WHATSAPP_NUMBER, type Product } from "@/lib/catalog";

/**
 * HAFIZ NUTS - shared SEO metadata and structured data.
 *
 * ## Why every page builds a full `openGraph` / `twitter` object
 *
 * Next merges metadata from a layout into its pages **shallowly**: a page
 * that sets `openGraph` replaces the root layout's object wholesale instead of
 * extending it. Leave a field out and it is simply gone - a policy page that
 * set only an OG title would preview with no image and no site name. And a
 * page that sets nothing inherits the homepage's `og:url`, telling every
 * social network that `/privacy` *is* the homepage.
 *
 * `pageMetadata` exists so no route has to remember that. It always emits the
 * complete set, plus a self-referencing canonical, for the one path it is
 * given.
 *
 * Isomorphic like `lib/catalog.ts`: no `node:fs`. Callers resolve images and
 * pass in a public path.
 */

export const SITE_NAME = "Hafiz Nuts";

/** Site-wide share card, generated by `scripts/generate-og-image.mjs`. */
export const DEFAULT_OG_IMAGE = {
  url: `${SITE_URL}/og-image.jpg`,
  width: 1200,
  height: 630,
  alt: "Hafiz Nuts Products",
} as const;

const LOCALE = "en_PK";

type PageMetadataInput = {
  /** Page-specific part only; the root `title.template` appends the brand. */
  title: string;
  description: string;
  /** Path from the site root, e.g. `/privacy`. */
  path: string;
  /** Public path of a page-specific share image; defaults to the site card. */
  image?: { path: string; alt: string };
};

export function pageMetadata({
  title,
  description,
  path,
  image,
}: PageMetadataInput): Metadata {
  const url = `${SITE_URL}${path}`;
  /* The template only applies to `<title>`, so social titles get the brand here. */
  const fullTitle = `${title} | ${SITE_NAME}`;
  const ogImage = image
    ? { url: `${SITE_URL}${image.path}`, alt: image.alt }
    : DEFAULT_OG_IMAGE;

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      title: fullTitle,
      description,
      url,
      siteName: SITE_NAME,
      images: [ogImage],
      locale: LOCALE,
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [ogImage.url],
    },
  };
}

